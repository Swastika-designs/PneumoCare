def _manifest(dataset_id: str) -> dict | None:
    folder = "chest_xray" if dataset_id == "kaggle_chest_xray" else dataset_id
    path = settings.raw_dir / folder / "_manifest.json"
    if path.exists():
        try:
            return json.loads(path.read_text())
        except json.JSONDecodeError:
            return None
    return None


def dataset_status() -> list[dict]:
    out = []
    for spec in DATASETS:
        item = dict(spec)
        item.setdefault("required", True)
        item.setdefault("note", None)
        if spec["path"] is None:
            item["available"] = True
        else:
            item["available"] = (settings.data_dir / spec["path"]).exists()
        manifest = _manifest(spec["id"])
        item["downloaded_at"] = (manifest.get("downloaded_at") or manifest.get("installed_at")) if manifest else None
        item["size_mb"] = round(sum(f["bytes"] for f in manifest["files"]) / 1e6, 1) if manifest else None
        out.append(item)
    return out


def is_available(dataset_id: str) -> bool:
    return any(d["id"] == dataset_id and d["available"] for d in dataset_status())


def _file_time(path: Path) -> str | None:
    if not path.exists():
        return None
    return datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc).isoformat()


